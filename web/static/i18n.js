function t(key, args, fallback) {
  var lang = document.documentElement.getAttribute('data-lang') || 'en';
  var dict = L[lang] || L['en'];
  var msg = dict[key] || (L['en'][key] || (typeof fallback === 'string' ? fallback : key));
  if (args) {
    for (var i = 0; i < args.length; i++) {
      // Escape args before substituting into messages that are often rendered
      // as innerHTML (e.g. providers.js). Prevents XSS via provider error text.
      var safeArg = (typeof args[i] === 'string') ? tEscapeHtml(args[i]) : args[i];
      msg = msg.replace('{' + i + '}', safeArg);
    }
  }
  return msg;
}

// tEscapeHtml escapes characters that are unsafe inside HTML text or
// attribute values. Delegates to the canonical window.escapeHtml in
// core-util.js (loaded first; i18n.js must not re-implement it).
function tEscapeHtml(s) {
  return window.escapeHtml(s);
}

// Playground translation lookup. Reads the same L dictionary (pg* keys were
// merged into L); falls back to the host t() then the bare key. NOTE: T does
// NOT escape its arguments while t does — that semantic difference is
// intentional (T renders into trusted templates, t into HTML text).
function T(key, ar) {
  var lang = document.documentElement.getAttribute('data-lang') || 'en';
  var dict = L[lang] || L['en'] || {};
  var s = dict[key];
  if (s != null) {
    if (ar && ar.length) {
      return s.replace(/\{(\d+)\}/g, function(_, i) { return ar[+i] != null ? ar[+i] : ''; });
    }
    return s;
  }
  if (typeof t === 'function') return t(key, ar);
  return key;
}

function currentLang() {
  return document.documentElement.getAttribute('data-lang') || 'en';
}

window.L = L; // single dictionary shared by t() and playground pgT()/T()

function setLang(lang) {
  if (lang !== 'en' && lang !== 'cn') lang = 'en';
  document.documentElement.setAttribute('data-lang', lang);
  localStorage.setItem('lang', lang);
  updateLangButton(lang);
  updateSidebarNav();
  if (typeof applyHeaderStatLabels === 'function') applyHeaderStatLabels();
  updateThemeModalLabels();
  if (typeof currentProviderId !== 'undefined' && currentProviderId) {
    if (typeof renderProviders === 'function') renderProviders(document.getElementById('page-content'));
  } else if (typeof navigateTo === 'function') {
    navigateTo(typeof currentPage !== 'undefined' ? currentPage : 'endpoint');
  }
  if (typeof updateUtilityNavLabel === 'function') updateUtilityNavLabel();
  if (typeof updateUtilityMenuState === 'function') updateUtilityMenuState();
  if (typeof updateGalleryNavLabel === 'function') updateGalleryNavLabel();
  if (typeof updateGalleryMenuState === 'function') updateGalleryMenuState();
  if (typeof updateDemoNavLabel === 'function') updateDemoNavLabel();
  if (typeof updateDemoMenuState === 'function') updateDemoMenuState();
}

function toggleLang() {
  setLang(currentLang() === 'en' ? 'cn' : 'en');
}

function updateThemeModalLabels() {
  var modalOverlay = document.getElementById('modal-overlay');
  if (!modalOverlay || modalOverlay.style.display === 'none') return;
  var modalTitle = modalOverlay.querySelector('.modal-header h3');
  if (modalTitle) modalTitle.textContent = t('appearance');
  var sectionTitles = modalOverlay.querySelectorAll('.style-modal-title');
  if (sectionTitles && sectionTitles.length >= 2) {
    sectionTitles[0].textContent = t('themeStyle');
    sectionTitles[1].textContent = t('langAndFontSize');
  }
  if (typeof ThemeSystem !== 'undefined') {
    if (typeof ThemeSystem.renderThemePicker === 'function') ThemeSystem.renderThemePicker('theme-modal-picker-container');
    if (typeof ThemeSystem.renderStylePicker === 'function') ThemeSystem.renderStylePicker('style-modal-picker-container');
  }
  if (typeof renderLangAndFontSizePicker === 'function') {
    renderLangAndFontSizePicker('lang-font-modal-container');
  }
}

function updateLangButton(lang) {
  var btn = document.getElementById('lang-btn');
  if (btn) btn.textContent = lang === 'en' ? 'EN' : 'CN';
}
